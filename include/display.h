#ifndef DISPLAY_H
#define DISPLAY_H

#include <stdint.h>

/* Framebuffer / raster console.
 *
 * This is split into two layers that can be reasoned about separately:
 *
 *   1. The framebuffer (display_fb.c). Drawing plus text. Depends on no
 *      hardware register layout, so it is checkable without a device.
 *
 *   2. Discovery (display_attach.c). Works out where the framebuffer is and
 *      what shape it is.
 *
 * The important structural fact, and the reason the API is shaped this way:
 * on A-series silicon the display pipeline is configured by the bootloader
 * *before* a checkm8 payload runs. A payload does not program the DSI PHY or
 * the raster timing generator from cold; it inherits a working scanout
 * engine and draws into the buffer the firmware left running.
 *
 * So display_fb_attach() adopts an existing buffer rather than allocating
 * one. Allocating a framebuffer in SRAM would produce a buffer nothing
 * scans out -- the panel would keep showing whatever the firmware drew.
 *
 * Only two panel-link registers are known well enough to touch (MIPI command
 * and status); see display_attach.c for what is assumed and what is not.
 */

/* Generated by scripts/gen_font.py. 5x7 glyphs in a 6x8 cell, 0x20-0x7E. */
#define FONT_FIRST 0x20
#define FONT_LAST  0x7E
#define FONT_GLYPH_W 5
#define FONT_GLYPH_H 7
#define FONT_CELL_W  6
#define FONT_CELL_H  8

extern const uint8_t font8x8[FONT_LAST - FONT_FIRST + 1][FONT_CELL_H];

typedef struct {
    uint32_t width;    /* pixels */
    uint32_t height;   /* pixels */
    uint32_t bpp;      /* 16 or 32 */
    uint32_t stride;   /* bytes per row */
    uint32_t *pixels;  /* base address, in device-visible memory */
    int      valid;
} display_fb_t;

#define DISPLAY_RGB565(r, g, b) \
    ((uint32_t)((((r) >> 3) << 11) | (((g) >> 2) << 5) | ((b) >> 3)))
#define DISPLAY_RGB888(r, g, b) \
    ((uint32_t)(0xff000000u | ((r) << 16) | ((g) << 8) | (b)))

/* Adopt a framebuffer the firmware already configured. Returns 0 on success,
 * -1 if the geometry is not one we can render into. */
int display_fb_attach(uint32_t base, uint32_t width, uint32_t height,
                      uint32_t stride_bytes, uint32_t bpp);
const display_fb_t *display_fb(void);
void display_fb_detach(void);

void display_fb_pixel(uint32_t x, uint32_t y, uint32_t pixel);
void display_fb_fill(uint32_t pixel);
void display_fb_fill_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h,
                          uint32_t pixel);
void display_fb_stroke_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h,
                            uint32_t pixel);

/* Scrolling text console over the current framebuffer. Silently does nothing
 * if no framebuffer is attached, so it is safe to call unconditionally. */
void display_console_init(uint32_t fg, uint32_t bg);
void display_console_putc(char c);
void display_console_write(const char *s);
void display_console_clear(void);
uint32_t display_console_cursor(void);

/* Panel link and geometry discovery (display_attach.c). */

/* Where the bootloader left the display configured. Zeroed if discovery did
 * not run or did not find anything usable. */
typedef struct {
    uint32_t base;         /* framebuffer base address */
    uint32_t width;
    uint32_t height;
    uint32_t stride_bytes; /* rowBytes */
    uint32_t bpp;          /* depth in bits */
    int      found;
} display_info_t;

const display_info_t *display_info(void);

/* Read the framebuffer geometry the firmware published in its device tree.
 * `dtb` is the device tree pointer handed over at entry (x0). Returns 0 if
 * geometry was recovered, negative if not. Does not map or draw. */
int display_probe_device_tree(uint64_t dtb);

/* Adopt the discovered framebuffer and point the console at it. Returns 0 on
 * success. */
int display_attach_discovered(void);

/* MIPI DSI command channel. These two offsets are the only panel registers
 * this driver asserts it knows. Returns 0 on success. */
int display_mipi_command(uint32_t cmd);

#endif /* DISPLAY_H */